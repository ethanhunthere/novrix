/**
 * Normalizes an indicator key, panel ID, or code to retrieve its rich metadata.
 */
export function getIndicatorMetadata(identifier: string): IndicatorMetadata | undefined {
  if (!identifier) return undefined;
  const cleanId = identifier.toLowerCase().trim().replace(/^indicator-/, '');

  // Direct lookup
  if (INDICATOR_METADATA[cleanId]) {
    return INDICATOR_METADATA[cleanId];
  }

  // Lookup by aliases or code or title
  for (const meta of Object.values(INDICATOR_METADATA)) {
    if (meta.code.toLowerCase() === cleanId) return meta;
    if (meta.title.toLowerCase() === cleanId) return meta;
    if (meta.aliases?.some(a => a.toLowerCase() === cleanId || a.toLowerCase().replace(/^indicator-/, '') === cleanId)) {
      return meta;
    }
  }

  return undefined;
}
